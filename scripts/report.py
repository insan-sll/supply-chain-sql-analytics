"""Run every query and write docs/RESULTS.md (question, finding, SQL, result)."""

from __future__ import annotations

from pathlib import Path

import pandas as pd

from scsql.db import build
from scsql.findings import finding
from scsql.questions import load_questions

OUT = Path(__file__).resolve().parent.parent / "docs" / "RESULTS.md"


def to_markdown(df: pd.DataFrame, max_rows: int = 12) -> str:
    shown = df.head(max_rows)
    head = "| " + " | ".join(shown.columns) + " |"
    rule = "| " + " | ".join("---" for _ in shown.columns) + " |"
    rows = ["| " + " | ".join("" if pd.isna(v) else str(v) for v in row) + " |" for row in shown.itertuples(index=False)]
    more = [f"\n_{len(df) - max_rows} more rows not shown._"] if len(df) > max_rows else []
    return "\n".join([head, rule, *rows, *more])


def main() -> None:
    con = build()
    parts = [
        "# Results",
        "",
        "Generated by `python scripts/report.py` from the seeded synthetic dataset. All numbers are invented.",
    ]
    for i, q in enumerate(load_questions(), start=1):
        df = con.execute(q.sql).df()
        parts += [
            "",
            f"## {i}. {q.title}",
            "",
            f"**Question:** {q.question}",
            "",
            f"**Finding:** {finding(q.id, df)}",
            "",
            f"SQL: [`sql/queries/{q.id}.sql`](../sql/queries/{q.id}.sql)",
            "",
            to_markdown(df),
        ]
    OUT.write_text("\n".join(parts) + "\n", encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
